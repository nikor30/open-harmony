#!/usr/bin/env python3
"""Render a TrueType font into anti-aliased glyph tables for ohdraw.h.

Usage: mkfont.py font.ttf pixel_size name out.h

Covers ASCII 32-126 plus the German letters Ä Ö Ü ä ö ü ß and °, each as
4-bit coverage (two pixels per byte, high nibble first), with advance,
bearing and baseline offset in pixels. The glyph index for a character is
font_index() in ohdraw.h (ASCII, then the extras in the order above).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

EXTRA = "ÄÖÜäöüß°"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__.strip())
    path, size, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    data = bytearray()
    glyphs = []
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch)
        adv = round(font.getlength(ch))
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            px = img.load()
            for y in range(h):
                row = [px[x, y] >> 4 for x in range(w)] + [0]
                for x in range(0, w, 2):
                    data.append(row[x] << 4 | row[x + 1])
        glyphs.append((off, w, h, x0, y0 - ascent, adv))
    with open(out, "w") as f:
        f.write(f"/* {name}: generated by tools/qnx/mkfont.py from "
                f"{path.rsplit('/', 1)[-1]} at {size} px (SIL Open Font License). */\n")
        f.write(f"static const unsigned char {name}_bits[{max(1, len(data))}] = {{\n")
        for i in range(0, len(data), 16):
            f.write("\t" + ", ".join(str(b) for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write(f"static const struct ohglyph {name}_glyphs[{len(glyphs)}] = {{\n")
        for off, w, h, bx, by, adv in glyphs:
            f.write(f"\t{{{off}, {w}, {h}, {bx}, {by}, {adv}}},\n")
        f.write("};\n")
        f.write(f"static const struct ohfont {name} = {{ {name}_bits, {name}_glyphs, "
                f"{ascent}, {descent} }};\n")
    print(f"{out}: {len(glyphs)} glyphs, {len(data)} bytes, ascent {ascent}, descent {descent}")


if __name__ == "__main__":
    main()
